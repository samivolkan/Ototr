begin;

alter table public.public_franchise_applications
  add column if not exists processing_consent boolean,
  add column if not exists consent_captured_at timestamptz,
  add column if not exists privacy_evidence_sha256 text,
  add column if not exists processing_evidence_sha256 text,
  add column if not exists commercial_evidence_sha256 text;

alter table public.public_franchise_applications
  add constraint public_franchise_privacy_evidence_sha256_check
    check (privacy_evidence_sha256 is null or privacy_evidence_sha256 ~ '^[0-9a-f]{64}$'),
  add constraint public_franchise_processing_evidence_sha256_check
    check (processing_evidence_sha256 is null or processing_evidence_sha256 ~ '^[0-9a-f]{64}$'),
  add constraint public_franchise_commercial_evidence_sha256_check
    check (commercial_evidence_sha256 is null or commercial_evidence_sha256 ~ '^[0-9a-f]{64}$');

create or replace function public.franchise_bind_public_consent_evidence()
returns trigger
language plpgsql
security definer
set search_path=''
as $$
declare
  v_captured_at timestamptz := statement_timestamp();
  v_version text := nullif(trim(new.consent_version),'');
begin
  -- Evidence is generated by PostgreSQL. Browser supplied digests are never trusted.
  new.consent_captured_at := v_captured_at;
  new.privacy_evidence_sha256 := case when new.kvkk_consent and v_version is not null then
    encode(extensions.digest(convert_to(concat_ws('|','OTOTR_FRANCHISE_CONSENT_V1',new.id::text,'privacy_notice','granted',v_version,v_captured_at::text),'UTF8'),'sha256'),'hex')
  else null end;
  new.processing_evidence_sha256 := case when new.processing_consent is not null and v_version is not null then
    encode(extensions.digest(convert_to(concat_ws('|','OTOTR_FRANCHISE_CONSENT_V1',new.id::text,'data_processing',case when new.processing_consent then 'granted' else 'withdrawn' end,v_version,v_captured_at::text),'UTF8'),'sha256'),'hex')
  else null end;
  new.commercial_evidence_sha256 := case when v_version is not null then
    encode(extensions.digest(convert_to(concat_ws('|','OTOTR_FRANCHISE_CONSENT_V1',new.id::text,'commercial_communication',case when new.contact_consent then 'granted' else 'withdrawn' end,v_version,v_captured_at::text),'UTF8'),'sha256'),'hex')
  else null end;
  return new;
end;
$$;

revoke execute on function public.franchise_bind_public_consent_evidence() from public,anon,authenticated;

create trigger franchise_public_consent_evidence_trigger
before insert on public.public_franchise_applications
for each row execute function public.franchise_bind_public_consent_evidence();

create or replace function public.franchise_capture_public_application()
returns trigger
language plpgsql
security definer
set search_path=''
as $$
declare
  v_ready boolean := new.kvkk_consent
    and new.processing_consent is true
    and nullif(trim(new.consent_version),'') is not null
    and new.privacy_evidence_sha256 is not null
    and new.processing_evidence_sha256 is not null
    and new.commercial_evidence_sha256 is not null;
begin
  insert into public.franchise_public_intake_bridge(
    source_application_id,status,reason_code,consent_version,commercial_consent_declared
  ) values (
    new.id,
    case
      when not new.kvkk_consent then 'rejected_missing_privacy'
      when v_ready then 'ready_for_canonicalization'
      else 'awaiting_processing_consent'
    end,
    case
      when not new.kvkk_consent then 'PRIVACY_NOTICE_NOT_ACCEPTED'
      when v_ready then 'SEPARATE_CONSENTS_VERIFIED'
      when nullif(trim(new.consent_version),'') is null then 'CONSENT_VERSION_REQUIRED'
      else 'SEPARATE_PROCESSING_CONSENT_REQUIRED'
    end,
    nullif(trim(new.consent_version),''),
    new.contact_consent
  )
  on conflict(source_application_id) do nothing;
  return new;
end;
$$;

revoke execute on function public.franchise_capture_public_application() from public,anon,authenticated;

